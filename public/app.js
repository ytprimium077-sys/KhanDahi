const loader=document.getElementById("loader");
window.addEventListener("load",()=>setTimeout(()=>loader.classList.add("done"),900));
const nav=document.querySelector(".topbar");
window.addEventListener("scroll",()=>nav.classList.toggle("scrolled",scrollY>35));
const menu=document.querySelector(".hamb"), drawer=document.querySelector(".mobile-menu");
menu.addEventListener("click",()=>{menu.classList.toggle("open");drawer.classList.toggle("open")});
drawer.querySelectorAll("a").forEach(a=>a.addEventListener("click",()=>{menu.classList.remove("open");drawer.classList.remove("open")}));
const io=new IntersectionObserver(entries=>entries.forEach(e=>{if(e.isIntersecting){e.target.classList.add("show");io.unobserve(e.target)}}),{threshold:.12});
document.querySelectorAll(".reveal").forEach(x=>io.observe(x));
const vid=document.querySelector(".hero-video"); vid.addEventListener("error",()=>vid.style.display="none");
